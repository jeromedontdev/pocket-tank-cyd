#!/usr/bin/env python3
"""Pack the canonical generated icon pixels for the CYD SD backend."""
import argparse
import pathlib
import re
import struct
import zlib


def pack(source, output):
    text = source.read_text()
    arrays = {}
    for kind, name, body in re.findall(
        r"static const (uint16_t|uint8_t) (\w+)\[\d+\] = \{(.*?)\};", text, re.S
    ):
        values = [int(v.strip(), 0) for v in body.split(",") if v.strip()]
        arrays[name] = struct.pack("<" + ("H" if kind == "uint16_t" else "B") * len(values), *values)
    entries = re.findall(
        r"const icon_t (\w+) = \{\s*(\d+),\s*(\d+),\s*(\w+),\s*(\w+)\s*(?:,\s*(\d+)\s*)?\};", text
    )
    if not entries:
        raise ValueError("No canonical icon definitions found")
    blob = bytearray()
    definitions = ['/* Generated by pack_cyd_icons.py. */', '#include "icons.h"']
    for name, w, h, rgb, alpha, flags in entries:
        n = int(w) * int(h)
        flags = int(flags or 0)
        colors = arrays[rgb]
        if flags & 0x40000000:
            count = struct.unpack_from("<H", colors)[0] if len(colors) >= 2 else 0
            per_word = 4 if count <= 16 else 2
            if not 1 <= count <= 256 or len(colors) != 2 * (1 + count + (n + per_word - 1) // per_word):
                raise ValueError(f"Invalid RGB palette for {name}")
            words = struct.unpack("<" + "H" * ((n + per_word - 1) // per_word), colors[2 * (1 + count):])
            bits = 16 // per_word
            indices = [(words[i // per_word] >> ((i % per_word) * bits)) & ((1 << bits) - 1) for i in range(n)]
            if any(index >= count for index in indices):
                raise ValueError(f"Invalid RGB index for {name}")
            colors = b"".join(colors[2 * (1 + index):2 * (2 + index)] for index in indices)
        plane = arrays[alpha]
        if flags & 0x80000000:
            if len(plane) % 2 or any(plane[i] == 0 for i in range(0, len(plane), 2)):
                raise ValueError(f"Invalid alpha runs for {name}")
            plane = b"".join(bytes([plane[i + 1]]) * plane[i] for i in range(0, len(plane), 2))
        if len(colors) != n * 2 or len(plane) != n:
            raise ValueError(f"Invalid planes for {name}")
        if len(blob) & 1:
            blob.append(0)
        definitions.append(f"const icon_t {name} = {{ {w}, {h}, 0, 0, {len(blob)} }};")
        blob.extend(colors)
        blob.extend(plane)
    crc = zlib.crc32(blob)
    output.mkdir(parents=True, exist_ok=True)
    (output / "icons_sd.c").write_text("\n".join(definitions) + "\n")
    (output / "icons.bin").write_bytes(blob)
    (output / "icons_sd_bank.h").write_text(
        f'#define CYD_ICON_FILE "icons-{crc:08x}.bin"\n'
        f"#define CYD_ICON_BYTES {len(blob)}u\n"
        f"#define CYD_ICON_CRC 0x{crc:08x}u\n"
    )
    print(f"{len(entries)} icons, {len(blob)} bytes, CRC32 {crc:08x}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=pathlib.Path)
    parser.add_argument("output", type=pathlib.Path)
    args = parser.parse_args()
    pack(args.source, args.output)
