#!/usr/bin/env python3
"""gen_icons.py - bake assets/icons/*.png into common/icons.c + icons.h.

Full-color pixel-art icons, hand-drawn (the style: 16/24 px, hard edges,
three-tone shading). Each PNG becomes an icon_t: exact RGB565
pixels (palette-indexed when smaller) + a lossless raw/RLE alpha plane, blended by render.c's
blit_icon() (which can also scale alpha for dimming/unrevealed states).

Run from anywhere; paths are repo-relative to this file:
    ~/.venvs/pocket-tank/bin/python tools/gen_icons.py
"""
import os, re, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "icons")
OUT_C = os.path.join(ROOT, "common", "icons.c")
OUT_H = os.path.join(ROOT, "common", "icons.h")


def cname(fn):
    stem = os.path.splitext(fn)[0]
    return "icon_" + re.sub(r"[^a-z0-9]+", "_", stem.replace("icon_", "").lower()).strip("_")


def encode_alpha(alpha):
    runs = []
    for value in alpha:
        if runs and runs[-1][1] == value and runs[-1][0] < 255:
            runs[-1][0] += 1
        else:
            runs.append([1, value])
    encoded = [v for run in runs for v in run]
    return (encoded, 0x80000000) if len(encoded) < len(alpha) else (alpha, 0)


def encode_rgb(rgb):
    palette = list(dict.fromkeys(rgb))
    if len(palette) > 256:
        return rgb, 0
    lookup = {color: index for index, color in enumerate(palette)}
    indices = [lookup[color] for color in rgb]
    bits = 4 if len(palette) <= 16 else 8
    per_word = 16 // bits
    packed = [len(palette)] + palette + [
        sum(index << (bits * j) for j, index in enumerate(indices[i:i + per_word]))
        for i in range(0, len(indices), per_word)
    ]
    return (packed, 0x40000000) if len(packed) < len(rgb) else (rgb, 0)


def main():
    files = sorted(f for f in os.listdir(SRC) if f.endswith(".png"))
    if not files:
        sys.exit(f"no PNGs in {SRC}")
    decls, defs, table = [], [], []
    total = 0
    for fn in files:
        img = Image.open(os.path.join(SRC, fn)).convert("RGBA")
        w, h = img.size
        if w > 64 or h > 64:
            sys.exit(f"{fn}: {w}x{h} is too big for a UI icon (max 64)")
        px = list(img.getdata())
        rgb, alp = [], []
        for r, g, b, a in px:
            rgb.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
            alp.append(a)
        n = cname(fn)
        total += w * h * 3
        colors, rgb_flags = encode_rgb(rgb)
        defs.append(f"static const uint16_t {n}_rgb[{len(colors)}] = {{\n"
                    + wrap(", ".join(f"0x{v:04x}" for v in colors)) + "\n};")
        encoded, flags = encode_alpha(alp)
        flags |= rgb_flags
        defs.append(f"static const uint8_t {n}_a[{len(encoded)}] = {{\n"
                    + wrap(", ".join(str(v) for v in encoded)) + "\n};")
        table.append(f"const icon_t {n} = {{ {w}, {h}, {n}_rgb, {n}_a, {flags} }};")
        decls.append(f"extern const icon_t {n};")
    hdr = (
        "/* icons.h - GENERATED by tools/gen_icons.py from the assets/icons PNGs.\n"
        " * Do not edit by hand; re-run the script after changing the art. */\n"
        "#ifndef POCKET_TANK_ICONS_H\n#define POCKET_TANK_ICONS_H\n"
        "#include <stdint.h>\n\n"
        "typedef struct {\n    uint8_t w, h;\n    const uint16_t *rgb;\n    const uint8_t *a;\n"
        "    uint32_t offset;\n} icon_t;\n"
        "const icon_t *icons_resolve(const icon_t *icon);\n\n"
        "/* Indexed RGB stores exact colors, then four 4-bit or two 8-bit indices per word. */\n"
        "static inline uint16_t icon_rgb_at(const icon_t *icon, unsigned index) {\n"
        "    if (!(icon->offset & UINT32_C(0x40000000))) return icon->rgb[index];\n"
        "    unsigned colors = icon->rgb[0];\n"
        "    if (colors <= 16) {\n"
        "        unsigned packed = icon->rgb[1 + colors + (index >> 2)];\n"
        "        return icon->rgb[1 + ((packed >> ((index & 3) * 4)) & 15)];\n"
        "    }\n"
        "    unsigned packed = icon->rgb[1 + colors + (index >> 1)];\n"
        "    return icon->rgb[1 + ((packed >> ((index & 1) * 8)) & 255)];\n"
        "}\n\n"
        "/* Embedded alpha is lossless RLE when the high offset bit is set.\n"
        " * Bank-backed icons keep their existing raw planes and offsets. */\n"
        "typedef struct { const uint8_t *next; unsigned end; uint8_t value; } icon_alpha_t;\n"
        "static inline uint8_t icon_alpha_at(const icon_t *icon, icon_alpha_t *cursor, unsigned index) {\n"
        "    if (!(icon->offset & UINT32_C(0x80000000))) return icon->a[index];\n"
        "    while (cursor->end <= index) {\n"
        "        cursor->end += cursor->next[0]; cursor->value = cursor->next[1]; cursor->next += 2;\n"
        "    }\n"
        "    return cursor->value;\n"
        "}\n\n"
        + "\n".join(decls) + "\n\n#endif\n")
    src = (
        "/* icons.c - GENERATED by tools/gen_icons.py from the assets/icons PNGs. */\n"
        '#include "icons.h"\n\n' + "\n\n".join(defs) + "\n\n" + "\n".join(table) + "\n")
    open(OUT_H, "w").write(hdr)
    open(OUT_C, "w").write(src)
    print(f"wrote {len(files)} icons, {total / 1024:.1f} KB of pixel data")
    for f in files:
        print(f"  {cname(f)}")


def wrap(s, width=100):
    out, line = [], "    "
    for tok in s.split(", "):
        if len(line) + len(tok) + 2 > width:
            out.append(line.rstrip())
            line = "    "
        line += tok + ", "
    out.append(line.rstrip().rstrip(","))
    return "\n".join(out)


if __name__ == "__main__":
    main()
